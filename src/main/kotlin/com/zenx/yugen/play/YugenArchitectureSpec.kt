/**
 * Dual form-factor product flavors sharing a single applicationId (`com.zenx.yugen.play`)
 * so in-place updates and persisted libraries work seamlessly across Mobile and Android TV.
 */
enum class AppFormFactor(
    val flavorName: String,
    val castEnabled: Boolean,
    val leanbackUi: Boolean,
    val assetMarker: String,
) {
    MOBILE(
        flavorName = "mobile",
        castEnabled = true,
        leanbackUi = false,
        assetMarker = "",
    ),
    TV(
        flavorName = "tv",
        castEnabled = false,
        leanbackUi = true,
        assetMarker = "_tv",
    ),
}

/**
 * Supported ABI splits and universal APK fallback generated by `app/build.gradle.kts`.
 */
enum class TargetAbi(
    val abiName: String,
    val isUniversal: Boolean,
) {
    UNIVERSAL(abiName = "universal", isUniversal = true),
    ARM64_V8A(abiName = "arm64-v8a", isUniversal = false),
    ARMEABI_V7A(abiName = "armeabi-v7a", isUniversal = false),
    ;

    fun releaseAssetName(formFactor: AppFormFactor): String =
        if (isUniversal) {
            "YugenPlay${formFactor.assetMarker}.apk"
        } else {
            "YugenPlay${formFactor.assetMarker}_$abiName.apk"
        }
}

