/**
 * Local mDNS (`_yugenplay._tcp.`) + ephemeral `secp256k1` ECDH TV pairing contract.
 *
 * Binds both ephemeral 65-byte uncompressed public keys and 16-byte nonces into an HKDF
 * transcript to derive a 6-digit Short Authentication String (SAS) and AES-256-GCM session key.
 */
sealed interface DevicePairingContract {
    enum class HandshakePhase {
        IDLE,
        ADVERTISING_MDNS,
        DISCOVERING_TV,
        AWAITING_COMMIT,
        SAS_VERIFICATION_PENDING,
        TRANSCRIPT_CONFIRMED,
        CREDENTIAL_SEALED_SENT,
        PROVISIONED,
        REJECTED,
    }

    data class CryptoParameters(
        val curve: String = "secp256k1",
        val privateKeyBytes: Int = 32,
        val uncompressedPublicKeyBytes: Int = 65,
        val nonceBytes: Int = 16,
        val sessionKeyBytes: Int = 32,
        val gcmIvBytes: Int = 12,
        val gcmTagBits: Int = 128,
        val sasDigits: Int = 6,
    ) : DevicePairingContract

    sealed interface ProvisionedCredential : DevicePairingContract {
        data class AniListBearerToken(val encryptedAesGcmFrame: Boolean = true) : ProvisionedCredential
        data class MalPkceChallenge(val verifierOnTvOnly: Boolean = true) : ProvisionedCredential
    }
}

/**
 * In-app release update contract (`UpdateManager`) targeting GitHub Releases (`/releases/latest`)
 * with form-factor APK selection and API-level-aware package installer URI routing.
 */
sealed interface UpdateManifestContract {
    enum class OfferDecision {
        NONE,
        PROMPT_NEW_VERSION,
        QUIET_SAME_VERSION_REBUILD,
        IMPORTANT_REBUILD_PROMPT,
    }

    enum class InstallerUriStrategy(val minApi: Int, val maxApi: Int?) {
        LEGACY_EXTERNAL_FILE(minApi = 22, maxApi = 23),
        FILE_PROVIDER_CONTENT(minApi = 24, maxApi = null),
    }

    data class ReleaseAssetDescriptor(
        val versionName: String,
        val buildCode: Int?,
        val formFactor: AppFormFactor,
        val targetAbi: TargetAbi,
        val fileName: String = targetAbi.releaseAssetName(formFactor),
        val sizeBytes: Long,
        val downloadUrl: String,
    ) : UpdateManifestContract

    sealed interface CheckLifecycle : UpdateManifestContract {
        data object Idle : CheckLifecycle
        data object Checking : CheckLifecycle
        data class UpToDate(val latestPublishedVersion: String) : CheckLifecycle
        data class Available(val asset: ReleaseAssetDescriptor, val offer: OfferDecision) : CheckLifecycle
        data class Downloading(val asset: ReleaseAssetDescriptor, val progress: Float) : CheckLifecycle
        data class ReadyToInstall(val asset: ReleaseAssetDescriptor, val strategy: InstallerUriStrategy) : CheckLifecycle
        data class Failed(val errorCode: String) : CheckLifecycle
    }
}
