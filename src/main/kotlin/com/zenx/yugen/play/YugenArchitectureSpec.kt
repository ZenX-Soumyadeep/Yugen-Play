/**
 * Zero-reflection manual singleton DI container contract (`AppGraph`).
 *
 * Eliminates annotation-processor code generation and startup factory initialization overhead
 * on constrained Android TV processors while keeping unit-test graph checks deterministic.
 */
sealed interface AppGraphContract {
    data object Uninitialized : AppGraphContract

    data class HardwareSensed(
        val isTelevision: Boolean,
        val isLowRamDevice: Boolean,
        val memoryClassMb: Int,
    ) : AppGraphContract

    data class Ready(
        val hardware: HardwareSensed,
        val httpDiskCacheMb: Int,
        val dohEnabled: Boolean,
        val legacyTrustAnchorsActive: Boolean,
    ) : AppGraphContract
}

/**
 * Two-level bounded cache contract (`AppCache`) combining an in-memory LRU map with
 * independent atomic disk files and stale-while-revalidate refresh coalescing.
 */
sealed interface AtomicCacheContract {
    data class TierLimits(
        val memoryEntries: Int,
        val memoryBudgetBytes: Long,
        val diskEntries: Int,
        val shardLockCount: Int,
    ) : AtomicCacheContract {
        companion object {
            val STANDARD_DEVICE = TierLimits(
                memoryEntries = 128,
                memoryBudgetBytes = 16L * 1024L * 1024L,
                diskEntries = 1024,
                shardLockCount = 64,
            )
            val LOW_RAM_OR_TV = TierLimits(
                memoryEntries = 40,
                memoryBudgetBytes = 6L * 1024L * 1024L,
                diskEntries = 512,
                shardLockCount = 64,
            )
        }
    }

    sealed interface LookupOutcome<out T> : AtomicCacheContract {
        data class FreshHit<T>(val value: T, val ageMs: Long) : LookupOutcome<T>
        data class StaleRevalidating<T>(val value: T, val ageMs: Long) : LookupOutcome<T>
        data object Superseded : LookupOutcome<Nothing>
        data object Miss : LookupOutcome<Nothing>
    }
}

/**
